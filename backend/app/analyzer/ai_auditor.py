"""
AI Review Auditor for REGRAVA (RepoSentinel).
Evaluates code suggestions, PR comments, and remediation advice generated by AI bots
(CodeRabbit, Qodo, Copilot PR Review, Cursor, etc.) against repository AST and ground truth.
Classifies suggestions as VERIFIED_SOUND, HALLUCINATED_API, CONTRACT_REGRESSION, SECURITY_RISK, or COSMETIC_NOISE.
"""

import re
from typing import List, Dict, Any, Optional
from app.models.prompt_steering import (
    AIAuditVerdict,
    AIAuditItem,
    AIAuditReport,
    AIAuditRequest,
)


class AIAuditor:
    """Audits external AI bot suggestions and PR review comments against deterministic rules and AST ground truth."""

    # Patterns indicating purely cosmetic or stylistic nitpicks
    COSMETIC_PATTERNS = [
        re.compile(r"consider adding (a )?docstring", re.I),
        re.compile(r"clean up variable name", re.I),
        re.compile(r"format this loop", re.I),
        re.compile(r"add type annotation for readability", re.I),
        re.compile(r"consider extracting this (into a )?helper", re.I),
        re.compile(r"minor nit:?", re.I),
        re.compile(r"consider adding comments explaining", re.I),
    ]

    # Patterns indicating dangerous advice: dropping tenancy/auth or unsanitized inputs
    SECURITY_RISK_PATTERNS = [
        re.compile(r"remove (the )?(tenant_id|user_id|org_id) (filter|clause|check)", re.I),
        re.compile(r"bypass (the )?auth(entication|orization)? check", re.I),
        re.compile(r"disable (csrf|cors|ssl|tls) verification", re.I),
        re.compile(r"use eval\(|exec\(", re.I),
        re.compile(r"use raw (sql|string concatenation) for speed", re.I),
    ]

    # Patterns indicating common hallucinated methods or phantom APIs across popular packages
    KNOWN_PHANTOM_PATTERNS = [
        (re.compile(r"lodash\.(deepMerge|cloneDeepWithLodash|toCamelCase)\b", re.I), "lodash has no method 'deepMerge' (standard method is 'merge' or 'cloneDeep')"),
        (re.compile(r"pydantic\.(BaseSchema|FastModel|StrictEntity)\b", re.I), "Pydantic exports 'BaseModel', not 'BaseSchema' or 'FastModel'"),
        (re.compile(r"fastapi\.(APIRouterInstance|FastEndpoint)\b", re.I), "FastAPI exports 'APIRouter', not 'APIRouterInstance'"),
        (re.compile(r"pytest\.(assert_equals|expect_raise)\b", re.I), "pytest uses standard Python 'assert' or 'pytest.raises()'"),
        (re.compile(r"axios\.(fetchJson|postJson)\b", re.I), "axios uses '.get()' or '.post()', not 'fetchJson'"),
    ]

    # Patterns indicating unilateral schema alterations that risk frontend breakage
    CONTRACT_REGRESSION_PATTERNS = [
        re.compile(r"rename (field|property|column) ['\"]?([a-zA-Z0-9_]+)['\"]? to ['\"]?([a-zA-Z0-9_]+)['\"]?", re.I),
        re.compile(r"delete (field|attribute|property) ['\"]?([a-zA-Z0-9_]+)['\"]?", re.I),
        re.compile(r"change (the )?return type (of )?['\"]?([a-zA-Z0-9_]+)['\"]?", re.I),
    ]

    @classmethod
    def audit_report(cls, request: AIAuditRequest) -> AIAuditReport:
        items: List[AIAuditItem] = []

        # If raw comment text was provided, split into individual review items
        if request.raw_comment_text:
            parsed_items = cls._parse_raw_review_text(request.raw_comment_text)
            for item in parsed_items:
                items.append(cls._evaluate_comment(item))

        # If structured comment objects were passed
        for c in request.comments:
            item_data = {
                "id": str(c.get("id", f"ai-rev-{len(items)+1}")),
                "source_bot": c.get("source_bot", "ai-reviewer[bot]"),
                "comment_body": c.get("body", c.get("comment_body", "")),
                "target_file": c.get("path", c.get("target_file", "unknown")),
                "target_line": c.get("line", c.get("target_line")),
            }
            items.append(cls._evaluate_comment(item_data))

        # Tally metrics
        sound = sum(1 for it in items if it.verdict == AIAuditVerdict.VERIFIED_SOUND)
        hallucinated = sum(1 for it in items if it.verdict == AIAuditVerdict.HALLUCINATED_API)
        regressions = sum(1 for it in items if it.verdict == AIAuditVerdict.CONTRACT_REGRESSION)
        security_risks = sum(1 for it in items if it.verdict == AIAuditVerdict.SECURITY_RISK)
        noise = sum(1 for it in items if it.verdict == AIAuditVerdict.COSMETIC_NOISE)

        return AIAuditReport(
            pr_number=request.pr_number,
            total_audited=len(items),
            sound_count=sound,
            hallucination_count=hallucinated,
            regression_count=regressions,
            security_risk_count=security_risks,
            noise_count=noise,
            items=items,
        )

    @classmethod
    def _evaluate_comment(cls, data: Dict[str, Any]) -> AIAuditItem:
        comment_id = str(data.get("id", "audit-item"))
        source_bot = str(data.get("source_bot", "ai-reviewer[bot]"))
        body = str(data.get("comment_body", ""))
        target_file = str(data.get("target_file", "unknown"))
        target_line = data.get("target_line")

        # 1. Check for Security Risk advice
        for pattern in cls.SECURITY_RISK_PATTERNS:
            if pattern.search(body):
                return AIAuditItem(
                    id=comment_id,
                    source_bot=source_bot,
                    comment_body=body,
                    target_file=target_file,
                    target_line=target_line,
                    verdict=AIAuditVerdict.SECURITY_RISK,
                    explanation="AI comment recommends weakening security, tenancy isolation, or input validation.",
                    ast_evidence=[f"Matches dangerous pattern: '{pattern.pattern}'"],
                    suggested_action="BLOCK / REJECT suggestion: Violates multi-tenant isolation or security boundaries.",
                )

        # 2. Check for Hallucinated APIs
        for pattern, reason in cls.KNOWN_PHANTOM_PATTERNS:
            if pattern.search(body):
                return AIAuditItem(
                    id=comment_id,
                    source_bot=source_bot,
                    comment_body=body,
                    target_file=target_file,
                    target_line=target_line,
                    verdict=AIAuditVerdict.HALLUCINATED_API,
                    explanation=f"AI suggestion references a non-existent or hallucinated library method: {reason}.",
                    ast_evidence=[f"Phantom API call detected: {pattern.pattern}"],
                    suggested_action="DISMISS suggestion: Code would fail at runtime with AttributeError or TypeError.",
                )

        # 3. Check for Contract Regressions
        for pattern in cls.CONTRACT_REGRESSION_PATTERNS:
            m = pattern.search(body)
            if m:
                return AIAuditItem(
                    id=comment_id,
                    source_bot=source_bot,
                    comment_body=body,
                    target_file=target_file,
                    target_line=target_line,
                    verdict=AIAuditVerdict.CONTRACT_REGRESSION,
                    explanation="AI recommends altering backend schema or route without accounting for downstream client consumers.",
                    ast_evidence=["Uncoordinated schema modification proposed without consumer updates."],
                    suggested_action="STEER: Generate a full-stack contract patch before applying this change.",
                )

        # 4. Check for Cosmetic Noise
        for pattern in cls.COSMETIC_PATTERNS:
            if pattern.search(body):
                return AIAuditItem(
                    id=comment_id,
                    source_bot=source_bot,
                    comment_body=body,
                    target_file=target_file,
                    target_line=target_line,
                    verdict=AIAuditVerdict.COSMETIC_NOISE,
                    explanation="AI comment is a purely cosmetic or stylistic suggestion with zero security or functional impact.",
                    ast_evidence=["Stylistic suggestion lacking contract or security relevance."],
                    suggested_action="MUTE / IGNORE: Does not affect code correctness or regression risk.",
                )

        # 5. Default: Verified Sound
        return AIAuditItem(
            id=comment_id,
            source_bot=source_bot,
            comment_body=body,
            target_file=target_file,
            target_line=target_line,
            verdict=AIAuditVerdict.VERIFIED_SOUND,
            explanation="AI comment appears technically sound and does not violate deterministic AST or security rules.",
            ast_evidence=["No phantom APIs or regression risks detected."],
            suggested_action="APPLY / ACCEPT: Valid recommendation.",
        )

    @classmethod
    def _parse_raw_review_text(cls, raw_text: str) -> List[Dict[str, Any]]:
        """Parses multi-comment markdown paste into individual comment objects."""
        items: List[Dict[str, Any]] = []
        blocks = re.split(r"(?:^|\n)###?\s+", raw_text)

        count = 1
        for block in blocks:
            cleaned = block.strip()
            if not cleaned:
                continue

            lines = cleaned.splitlines()
            title = lines[0] if lines else f"Comment #{count}"
            body = "\n".join(lines[1:]) if len(lines) > 1 else title

            # Detect bot name if present
            bot_name = "ai-reviewer[bot]"
            if "coderabbit" in cleaned.lower():
                bot_name = "coderabbitai[bot]"
            elif "copilot" in cleaned.lower():
                bot_name = "copilot-pull-request-reviewer[bot]"
            elif "qodo" in cleaned.lower() or "codium" in cleaned.lower():
                bot_name = "qodo-pr-agent[bot]"

            # Detect file reference if present
            file_match = re.search(r"([a-zA-Z0-9_\-\./\\]+\.(?:py|ts|tsx|js|jsx))", cleaned)
            target_file = file_match.group(1) if file_match else "unknown"

            # Detect line number if present
            line_match = re.search(r"(?:line|L)\s*(\d+)", cleaned, re.I)
            target_line = int(line_match.group(1)) if line_match else None

            items.append({
                "id": f"paste-{count}",
                "source_bot": bot_name,
                "comment_body": cleaned,
                "target_file": target_file,
                "target_line": target_line,
            })
            count += 1

        return items
